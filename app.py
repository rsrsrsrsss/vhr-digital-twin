import streamlit as st
import numpy as np
import pandas as pd
import plotly.express as px

# Настройка на страницата
st.set_page_config(
    page_title="ВВЕР-1000 Дигитален Двойник — АЕЦ Козлодуй",
    page_icon="⚛️",
    layout="wide"
)

st.title("⚛️ Дигитален Двойник на ВХР — Блок 5, АЕЦ Козлодуй")

# Странично меню за избор на 2-та основни модула
st.sidebar.title("🕹️ Главно меню")
module = st.sidebar.radio(
    "Изберете модул:",
    [
        "1. Оперативен мониторинг & Управление на ВХР",
        "2. Корозионен симулатор & Пасивация на метали"
    ]
)

# Инициализация на Session State за автоматична корекция
if 'auto_fix' not in st.session_state:
    st.session_state.auto_fix = False

# ================= =========================================
# МОДУЛ 1: МОНИТОРИНГ И УПРАВЛЕНИЕ НА ВХР (1-ви и 2-ри контур)
# ==========================================================
if module == "1. Оперативен мониторинг & Управление на ВХР":
    st.header("📊 1. Интегриран оперативен мониторинг & Управление")
    st.caption("Симулиране и управление на водно-химичния режим за Първи и Втори контур (ВВЕР-1000)")

    # СТРАНИЧЕН ПАНЕЛ ЗА УПРАВЛЕНИЕ
    st.sidebar.markdown("---")
    st.sidebar.subheader("🎛️ Параметри за управление (Първи контур)")
    
    primary_temp = st.sidebar.slider("Работна температура Т1 (°C)", 280.0, 325.0, 301.0, 0.5)
    h3bo3 = st.sidebar.slider("Борна киселина H3BO3 (g/kg)", 0.0, 10.0, 3.5, 0.1)
    
    # Ако е натиснат бутона за Авто-корекция, задаваме оптимални базови стойности
    if st.session_state.auto_fix:
        k_default = 12.0
        nh3_default = 18.0
        h2_default = 45.0
        o2_default = 0.0
    else:
        k_default = 6.0
        nh3_default = 10.0
        h2_default = 35.0
        o2_default = 8.0

    # Всички слайдери за Първи контур
    k_mg = st.sidebar.slider("Калиева основа / K+ (mg/dm³)", 0.0, 20.0, k_default, 0.5)
    nh3_mg = st.sidebar.slider("Дозиране на Амоняк NH3 (mg/dm³)", 0.0, 30.0, nh3_default, 1.0)
    h2_input = st.sidebar.slider("Молекулярен Водород H2 (Ncm³/kg)", 0.0, 150.0, h2_default, 1.0)
    o2_input = st.sidebar.slider("Приток на Разтворен O2 (ppb)", 0.0, 50.0, o2_default, 1.0)
    
    st.sidebar.subheader("🎛️ Параметри за управление (Втори контур)")
    eta_ppm = st.sidebar.slider("Дозиране на ЕТА (mg/dm³)", 0.0, 5.0, 1.8, 0.1)
    cond_leak = st.sidebar.slider("Приток в кондензатора (L/h)", 0.0, 5.0, 0.0, 0.1)

    # Термодинамични и химически изчисления за Първи контур
    ph_25_p1 = 7.0 + 0.12 * k_mg - 0.08 * h3bo3
    ph_t_p1 = ph_25_p1 - (primary_temp - 25.0) * 0.0072

    # Реална концентрация на O2 (входен O2 минус неутрализирания от H2)
    effective_o2 = max(0.0, o2_input - (h2_input / 10.0))

    # ПРОВЕРКА ЗА АВАРИЕН РЕЖИМ (Свободен газ от прекомерен H2)
    is_emergency_scram = h2_input > 100.0
    power_mw = "0 MWth (ААЗ СРАБОТИЛА!)" if is_emergency_scram else "3000 MWth"
    power_delta = "🚨 АВАРИЙНО СПИРАНЕ" if is_emergency_scram else "100%"

    # Метрики на живо
    col1, col2, col3, col4 = st.columns(4)
    col1.metric("Теплинна мощност", power_mw, power_delta)
    col2.metric("pH_T (Първи контур)", f"{ph_t_p1:.2f}", delta="В норма (7.0-7.3)" if 7.0 <= ph_t_p1 <= 7.3 else "Отклонение")
    col3.metric("Разтворен H2", f"{h2_input:.1f} Ncm³/kg", "🚨 Газова фаза!" if is_emergency_scram else "Норма: 30-60 Ncm³/kg")
    col4.metric("Разтворен O2 (Първи контур)", f"{effective_o2:.1f} ppb", "Критично!" if effective_o2 > 5.0 else "✅ < 5 ppb")

    st.markdown("---")

    # Графики за 1-ви и 2-ри контур
    t1, t2 = st.tabs(["Първи контур (Борно-Калиев режим & Газове)", "Втори контур (Питателна вода & ЕТА)"])

    time_series = pd.date_range(end=pd.Timestamp.now(), periods=25, freq='2min')
    np.random.seed(42)

    with t1:
        st.subheader("Първи контур: Динамика на реагентите и разтворените газове")
        df_p1 = pd.DataFrame({
            "Време": time_series,
            "H3BO3 (g/kg)": np.random.normal(h3bo3, 0.02, 25),
            "Калий K+ (mg/dm³)": np.random.normal(k_mg, 0.1, 25),
            "Разтворен H2 (Ncm³/kg)": np.random.normal(h2_input, 0.5, 25),
            "Разтворен O2 (ppb)": np.random.normal(effective_o2, 0.1 if effective_o2 > 0 else 0, 25)
        })
        fig_p1 = px.line(df_p1, x="Време", y=["H3BO3 (g/kg)", "Калий K+ (mg/dm³)", "Разтворен H2 (Ncm³/kg)", "Разтворен O2 (ppb)"], 
                         title="Мониторинг на Бор, Калий, Разтворен Водород и Кислород")
        st.plotly_chart(fig_p1, use_container_width=True)

    with t2:
        st.subheader("Втори контур: Водно-химичен режим & Електропроводимост")
        df_p2 = pd.DataFrame({
            "Време": time_series,
            "ЕТА (mg/dm³)": np.random.normal(eta_ppm, 0.03, 25),
            "Относителна проводимост χc (µS/cm)": 0.11 + cond_leak * 0.05 + np.random.normal(0, 0.002, 25)
        })
        fig_p2 = px.line(df_p2, x="Време", y=["ЕТА (mg/dm³)", "Относителна проводимост χc (µS/cm)"], title="Динамика на Втори Контур")
        st.plotly_chart(fig_p2, use_container_width=True)

    # ОПЕРАТИВНА КАРТА & АВТОМАТИЧНА КОРЕКЦИЯ
    st.markdown("---")
    st.subheader("📋 Оперативна карта & Автоматизирано управление")

    has_issue = is_emergency_scram or (cond_leak > 0.2) or (effective_o2 > 5.0) or (ph_t_p1 < 7.00 or ph_t_p1 > 7.30)

    if has_issue:
        if is_emergency_scram:
            st.error("🚨🚨🚨 АВАРИЕН СИНАЛ: ПРЕВИШЕНА ГРАНИЦА НА РАЗТВОРИМОСТ НА ВОДОРОДА (H2 > 100 Ncm³/kg)!")
            st.markdown(f"""
            * **📍 Локализация:** Първи циркулационен контур (Горна част на реактора / Хорда на ГЦП).
            * **🔍 Причина:** Натрупване на прекомерно количество молекулярен водород (`{h2_input:.1f} Ncm³/kg`), надвишаващо предела на разтворимост при $301^\circ\text{{C}}$.
            * **💥 Риск за безопасността:** Образуване на свободна газова фаза (газов джоб / мехурчета), кавитация на главните циркулационни помпи и влошено охлаждане на активната зона.
            * **⚡ Действие на защитите:** Сработила Аварийна защита (ААЗ). Реакторът е изключен!
            * **🛠️ Препоръка към химик-инженера:** Намалете дозирането на водород/амоняк и продухайте газовата възглавница за възстановяване на нормалния воден режим.
            """)
        
        st.warning("⚠️ Желаете ли автоматична корекция на параметрите за изход от рисковия режим?")
        
        # БУТОНИ ЗА АВТОМАТИЧНА КОРЕКЦИЯ
        col_btn1, col_btn2 = st.columns(2)
        with col_btn1:
            if st.button("🤖 Да -> Коригирай автоматично нужните реагенти"):
                st.session_state.auto_fix = True
                st.rerun()
        with col_btn2:
            if st.button("❌ Не -> Остави за ръчна интервенция (Препоръка)"):
                st.session_state.auto_fix = False
                st.rerun()

        st.markdown("---")

        if not is_emergency_scram:
            if cond_leak > 0.2:
                st.error("🚨 ВНИМАНИЕ: Приток в кондензатора!")
                st.markdown(f"""
                * **📍 Локализация:** Охладителна система на кондензационния тракт.
                * **🔍 Причина:** Приток на неутрални/агресивни примеси (Дебит: `{cond_leak} L/h`).
                * **⚠️ Риск при забавяне:** Повишена обща корозия и питинг по тръбния сноп на парогенераторите.
                * **🛠️ Препоръка към химик-инженера:** Повишете дозирането на ЕТА и увеличете продухването на парогенераторите.
                """)
            
            elif effective_o2 > 5.0:
                st.error("🚨 ВНИМАНИЕ: Повишен разтворен Кислород (O2) в Първи контур!")
                st.markdown(f"""
                * **📍 Локализация:** Първи циркулационен контур.
                * **🔍 Причина:** Недостатъчен водороден покрив (`H2 = {h2_input:.1f} Ncm³/kg`) за пълно свързване на радиолитичния кислород.
                * **⚠️ Риск при забавяне:** Риск от междукристално корозионно напукване под напрежение (SCC) на аустенитните стомани (08Х18Н10Т) и авариен престой.
                * **🛠️ Препоръка към химик-инженера:** Увеличете дозирането на H2 / Амоняк за достигане на 30–60 Ncm³/kg.
                """)

            elif ph_t_p1 < 7.00 or ph_t_p1 > 7.30:
                st.warning("⚠️ ПРЕДУПРЕЖДЕНИЕ: Отклонение в pH_T (Борно-Калиев координационен график)!")
                st.markdown(f"""
                * **📍 Локализация:** Първи контур.
                * **🔍 Причина:** Небалансирано съотношение между H3BO3 (`{h3bo3} g/kg`) и K+ (`{k_mg} mg/dm³`).
                * **⚠️ Риск при забавяне:** Разтваряне и пренасяне на корозионни продукти върху обвивките на ТВЕЛ-ите (активиране на CRUD отлагания).
                * **🛠️ Препоръка към химик-инженера:** Коригирайте дозирането на Калиева основа (KOH), за да достигнете pH_T = 7.10 - 7.20.
                """)
    else:
        st.success("✅ Всички химически параметри на Борно-Калиевия режим са идеално балансирани. Няма риск от корозия.")

# ================= =========================================
# МОДУЛ 2: КОРОЗИОНЕН СИМУЛАТОР & ПАСИВАЦИЯ НА МЕТАЛИ
# ==========================================================
elif module == "2. Корозионен симулатор & Пасивация на метали":
    st.header("🔬 2. Лаборатория за корозионни изпитания и пасивация")
    st.caption("Физикохимичен анализ на устойчивостта на конструкционни метали спрямо работните параметри")

    col_in1, col_in2, col_in3 = st.columns(3)

    with col_in1:
        metal = st.selectbox(
            "Изберете конструкционен метал / сплав:",
            [
                "Аустенитна неръждаема стомана (08Х18Н10Т)",
                "Въглеродна стомана (20К / 16ГС)",
                "Никелова сплав / Инокъл 690"
            ]
        )

    with col_in2:
        fluid = st.selectbox(
            "Агрегатно състояние на флуида:",
            [
                "💧 Водна фаза (Течна)",
                "🌫️ Паро-газова фаза (Суха пара)",
                "🫧 Двуфазна среда (Вода + Пара / Влажна пара)"
            ]
        )

    with col_in3:
        work_temp = st.slider("Работна температура (°C)", 25.0, 350.0, 280.0, 5.0)

    # Допълнителни химически фактори
    st.markdown("### 🧪 Входни химически условия за изпитването")
    c_f1, c_f2, c_f3 = st.columns(3)
    ph_val = c_f1.slider("pH на средата", 4.0, 11.0, 9.2, 0.1)
    o2_conc = c_f2.number_input("Разтворен O2 (ppb)", 0, 500, 10)
    cl_conc = c_f3.number_input("Хлоридни йони Cl- (ppb)", 0, 1000, 5)

    # ФИЗИКОХИМИЧЕН МАТЕМАТИЧЕСКИ МОДЕЛ ЗА КОРОЗИЯ И ПАСИВАЦИЯ
    if "Въглеродна" in metal:
        base_rate = 0.05 * np.exp((work_temp - 100)/100)
        if ph_val < 9.0:
            base_rate *= 2.5
        if fluid == "🫧 Двуфазна среда (Вода + Пара / Влажна пара)":
            base_rate *= 3.0
            
        if ph_val >= 9.2 and o2_conc < 20 and fluid != "🫧 Двуфазна среда (Вода + Пара / Влажна пара)":
            passivated = True
            film_type = "Магнетитен защитен филм (Fe3O4)"
        else:
            passivated = False
            film_type = "Няма плътен пасивационен филм (Активно разтваряне)"

    elif "Аустенитна" in metal:
        base_rate = 0.003 * np.exp((work_temp - 100)/200)
        if cl_conc > 100 and work_temp > 150:
            base_rate *= 4.0
        
        passivated = True
        film_type = "Хромов оксиден пасивационен слой (Cr2O3)"

    else:
        base_rate = 0.001 * np.exp((work_temp - 100)/250)
        passivated = True
        film_type = "Високостабилен Никелово-Хромов пасивационен филм"

    st.markdown("---")
    st.subheader("📊 Резултати от изпитването")

    res1, res2, res3 = st.columns(3)
    res1.metric("Прогнозна скорост на корозия", f"{base_rate:.4f} mm/year")
    
    if passivated:
        res2.success("🛡️ СТАТУС: Металът ПАСИВИРА")
    else:
        res2.error("💥 СТАТУС: НАСТЪПВА КОРОЗИЯ")

    res3.info(f"🔬 Образуван филм: {film_type}")

    # Детайлен механизъм
    st.markdown("### 🔍 Диагноза на корозионния механизъм:")
    if not passivated and "Въглеродна" in metal:
        st.error("⚠️ **Висок риск от Ерозионно-корозионно износване (FAC)!** Защитният магнетитен слой се разтваря интензивно поради ниското pH или високата скорост на двуфазния поток.")
    elif "Аустенитна" in metal and cl_conc > 100:
        st.warning("⚠️ **Риск от питингова корозия и Корозионно напукване (SCC)!** Наличието на хлориди над 100 ppb при висока температура разрушава локално пасивационния Cr2O3 слой.")
    else:
        st.success("✅ **Отлична корозионна устойчивост.** Металът формира стабилен защитен филм и запазва целостта си при избраните условия.")
